// 큰 정수를 잃지 않는 JSON 파싱 (순수 함수, **import 없음**)
//
// ── 왜 필요한가 (2026-09-02 실주문 테스트에서 발견) ────────────────────────
// 바이낸스가 심볼마다 다른 주문번호 체계를 쓴다:
//
//   BTCUSDT   1121692450577          13자리 — JS가 정확히 담는다
//   ETHUSDT   8389766268995766668    19자리 — **담지 못한다**
//
// JS의 안전 정수 한계는 `Number.MAX_SAFE_INTEGER`(9007199254740991, 16자리)다.
// 그 위는 `JSON.parse`가 가장 가까운 부동소수로 뭉갠다:
//
//   보낸 값   8389766268995766668
//   받은 값   8389766268995766000     ← 뒤 3자리 소실 (실측)
//
// 그 번호로 조회하면 거래소가 `Order does not exist.`를 돌려준다 —
// **미체결 취소·체결 감지·store 키가 전부 어긋난다.**
// BTCUSDT만 거래하던 동안에는 13자리라 드러날 일이 없었다.
//
// ── 어떻게 고치나 ──────────────────────────────────────────────────────────
// 파싱 **전에** 안전 범위를 넘는 정수를 따옴표로 감싸 문자열로 만든다.
// 우리 코드는 주문번호를 이미 대부분 `String(...)`으로 다루고, 거래소로 되돌려
// 보낼 때도 쿼리 문자열이라 문자열이 그대로 맞다.
//
// ⚠ **안전 범위 안의 수는 건드리지 않는다.** 자릿수가 아니라 값으로 판정한다 —
//   그래야 지금까지 숫자로 오던 것(13자리 주문번호, 타임스탬프, 알고 주문 id)이
//   그대로 숫자로 남아 기존 동작이 바뀌지 않는다.
// ⚠ 문자열 **안**의 숫자는 건드리면 안 된다. 그래서 앞에 `:` `[` `,`가 오고
//   뒤에 `,` `}` `]`가 오는 자리(= JSON에서 값이 놓이는 자리)만 본다.
//   문자열 안의 숫자 뒤에는 `"`나 다른 글자가 오므로 걸리지 않는다.

// 값 자리에 놓인 16자리 이상의 정수. 뒤 구분자는 소비하지 않는다(lookahead)
const BIG_INT = /([:[,])(\s*)(\d{16,})(?=\s*[,}\]])/g;

/**
 * 안전 범위를 넘는 정수를 문자열로 바꾼 JSON 텍스트.
 * (파싱하지 않는다 — 텍스트만 손본다. 테스트에서 눈으로 보기 위해 따로 낸다)
 */
function quoteBigInts(text) {
  if (typeof text !== "string") return text;
  return text.replace(BIG_INT, (m, pre, sp, digits) =>
    Number(digits) > Number.MAX_SAFE_INTEGER ? `${pre}${sp}"${digits}"` : m);
}

/**
 * `JSON.parse` 대체. 큰 정수는 **문자열로** 나온다.
 *
 * ⚠ 파싱에 실패하면 원래 오류를 그대로 던진다 — 조용히 null을 돌려주면
 *   응답이 깨진 것과 "빈 응답"을 구분할 수 없다.
 */
function parseBigInt(text) {
  return JSON.parse(quoteBigInts(text));
}

module.exports = { quoteBigInts, parseBigInt };
