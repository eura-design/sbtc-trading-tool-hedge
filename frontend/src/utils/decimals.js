// 단위 문자열의 유효 소수 자릿수 (순수 함수, **import 없음**)
//
// ── 왜 따로 있나 ───────────────────────────────────────────────────────────
// 호가 단위(`tickSize`)와 수량 단위(`stepSize`)의 자릿수를 뽑는 규칙이다.
// 2026-09-02에 심볼별 단위를 다루기 시작하면서 이 다섯 줄이 **일곱 곳에 복제**됐고,
// 하루 만에 둘이 갈렸다 — `splitTp.js`와 `paperBroker.js`만 지수 표기 방어가 빠져
// `1e-5`에서 **5가 아니라 0**을 냈다 (2026-09-03 감사에서 발견).
//
// 자릿수가 갈리면 **화면에 뜬 숫자와 거래소로 나가는 숫자가 달라진다.**
// 그 어긋남은 체결된 뒤에야 보인다. 그래서 한 곳만 둔다.
//
// ⚠ **backend/utils/round.js의 `decimalsOf`와 같은 규칙이어야 한다.**
//   프론트와 백엔드는 코드를 나눠 쓸 수 없어 두 벌이 불가피하다 —
//   둘 중 하나를 고치면 반드시 다른 쪽도 고칠 것. (`tests/decimals.test.js`가 지킨다)

/**
 * @param step `"0.00100000"` / `"0.10"` / `1` / `0.001` 같은 단위 값
 * @returns 유효 소수 자릿수. `"0.10"` → 1 (뒤의 0은 떼고 센다)
 *
 * ⚠ 뒤의 0을 떼는 이유: 바이낸스는 `"0.00100000"`처럼 채워 보내는데, 그대로 8을 쓰면
 *   `pricePrecision`이 3인 심볼에 소수 8자리를 보내 거래소가 거절한다.
 * ⚠ 지수 표기(`1e-5`)를 방어하는 이유: 값이 **숫자**로 흘러들어오면 JS가
 *   `String(0.00001)`은 `"0.00001"`로, `String(0.0000001)`은 `"1e-7"`로 만든다.
 *   방어가 없으면 소수점이 없다고 보고 **0자리**를 답한다.
 */
export function decimalsOf(step) {
  const s = String(step);
  if (/e/i.test(s)) {
    const n = Number(s);
    return n > 0 && n < 1 ? Math.max(0, -Math.floor(Math.log10(n))) : 0;
  }
  const dot = s.indexOf(".");
  return dot < 0 ? 0 : s.slice(dot + 1).replace(/0+$/, "").length;
}
