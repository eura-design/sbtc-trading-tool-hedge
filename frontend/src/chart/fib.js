//
// 트렌드라인/채널/원과 같은 계열의 **도형**이다. 좌표가 timestamp라 전 TF 공유이고,
// 저장은 useDrawableStore("fibs"), 선택·투명도·잠금·근접 알림은 도형 공통 인터페이스
// (chart/drawables.js)를 그대로 탄다. 지표 메뉴에 행이 있는 이유는 **레벨 목록이
// 전역 파라미터**라서지, 계산이 지표라서가 아니다.
//
// ── ⚠ 사용자 확정 사양 (2026-08-14, 임의 변경 금지) ──────────────────────────
// 아래 네 가지는 만들기 전에 사용자가 직접 고른 값이다. "트뷰 기본값이 저쪽이다"로
// 되돌리지 말 것 — 트뷰 기본값을 나란히 보여주고 고른 결과가 이것이다.
//
//   [F1] 레벨 목록은 **지표 메뉴에서 전역 편집** (도형별 아님).
//        → indicatorParams.fib.levels. 모든 피보나치 도형이 같은 목록을 쓴다
//   [F2] 구간 **채우기 없음 — 선만**. 반투명 밴드를 깔지 않는다
//   [F3] 라벨은 **비율만**. 가격·% 병기 안 함 (가격은 크로스헤어가 답한다)
//   [F4] 레벨 선은 **두 앵커 사이에만** 긋는다. 오른쪽/양쪽 연장 없음
//
// [F5] 앵커 방향은 트레이딩뷰와 같다: **첫 클릭 = 추세 시작(레벨 1), 둘째 클릭 = 추세 끝(레벨 0)**.
//   상승 되돌림이면 저점 → 고점 순으로 찍는다. 뒤집으면 0.236과 0.786이 자리를 바꿔
//   같은 두 점인데 트뷰와 다른 가격에 선이 생긴다.

// ⚠ **이 파일은 import가 없다 — 순수 계산만 둘 것** (pivotLevels.js와 같은 이유).
//   node에서 바로 `import`해 실제 값으로 검증할 수 있어야 한다. 픽셀 좌표 변환이
//   필요하면 hitDetection.js의 `fibXs`처럼 화면 쪽 파일에 두면 된다
//   (scales를 여기서 끌어오는 순간 d3 체인이 딸려와 node 실행이 깨진다).

// 지표 메뉴에서 고를 수 있는 후보 전체. 앞 7개가 트레이딩뷰 기본 되돌림,
// 뒤 3개는 확장(1 초과 = 추세 시작점을 뚫고 더 간 자리)이라 기본 체크 해제다.
export const FIB_ALL_LEVELS     = [0, 0.236, 0.382, 0.5, 0.618, 0.786, 1, 1.272, 1.414, 1.618];
export const FIB_DEFAULT_LEVELS = [0, 0.236, 0.382, 0.5, 0.618, 0.786, 1];

// 지그재그·트렌드라인과 같은 회색. 레벨마다 색을 달리하지 않는다 —
// 구분은 라벨(비율)이 하고, 7~10줄에 각각 색을 주면 캔들보다 선이 눈에 먼저 들어온다
export const FIB_COLOR = "#888888";

/**
 * 레벨 r의 가격.
 *
 * p1 = 추세 시작(레벨 1), p2 = 추세 끝(레벨 0) — [F5].
 *   선형: p2 + (p1 - p2) · r
 *   로그: p2 · (p1/p2)^r
 *
 * ⚠ **로그 모드에서는 로그 보간을 쓴다** (트레이딩뷰와 동일). 선형으로 계산하면
 *   로그 차트에서 0.5 선이 두 앵커의 시각적 한가운데에 놓이지 않아 "되돌림 절반"이라는
 *   말과 화면이 어긋난다. 채널(`ch.isLog`)처럼 생성 시점 값을 저장하지 않고 **현재 스케일**을
 *   보는 이유: 피보나치는 "지금 보고 있는 축에서의 비율"이 곧 의미라, 축을 바꾸면
 *   같이 따라가야 한다.
 */
export function fibPrice(p1, p2, r, isLog = false) {
  if (isLog && p1 > 0 && p2 > 0) return p2 * Math.pow(p1 / p2, r);
  return p2 + (p1 - p2) * r;
}

/**
 * 저장된 파라미터 → 실제로 그릴 레벨 배열 (오름차순, 정제 완료).
 *
 * 매 렌더에서 부르지 말 것 — 정렬이 들어간다. App.jsx가 useMemo로 한 번 만들어
 * 렌더·히트 판정·알림에 같은 배열을 나눠 준다 (셋이 어긋나면 안 보이는 선이 클릭된다).
 */
export function normFibLevels(raw) {
  const list = Array.isArray(raw) ? raw : FIB_DEFAULT_LEVELS;
  const out  = list.filter(r => typeof r === "number" && isFinite(r));
  return Array.from(new Set(out)).sort((a, b) => a - b);
}

/** 레벨 목록 → [{ r, price }] */
export function fibLevelPrices(fib, levels, isLog = false) {
  return levels.map(r => ({ r, price: fibPrice(fib.p1, fib.p2, r, isLog) }));
}

