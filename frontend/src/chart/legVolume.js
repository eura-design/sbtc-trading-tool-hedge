// 지그재그 레그의 거래량 — 순수 함수
//
// [LV1] 비교 대상은 "이전 상승 레그 vs 이번 상승 레그"다 (같은 방향끼리, 같은 지표끼리).
//   상승인데 거래량이 줄었으면 동력 약화(다이버전스) 신호로 읽는다.
//   ※ 예전에 x축을 손으로 드래그해 구간을 잡는 도구로 만들었다가 **폐기**했다 —
//     비교할 때마다 레그를 두 개씩 직접 그려야 해서 실제로 안 쓰게 된다는 피드백.
//     지그재그가 이미 레그를 계산하고 있으므로 hover에 얹는 쪽이 맞다. 되돌리지 말 것.
//
// [LV2] **합계가 아니라 최대값이다** (사용자 확정 — "피크치만 비교하고 싶어").
//   합계로 되돌리지 말 것. 합계는 레그 길이에 휘둘린다: 2봉짜리 레그와 12봉짜리 레그를
//   총합으로 비교하면 사실상 "어느 쪽이 오래 걸렸나"를 재게 된다.
//   피크는 봉 하나의 값이라 **길이와 무관**하고, "가장 센 한 방이 얼마였나"를 바로 답한다.
//   (실측: 봉 수와의 상관계수가 합계 0.76 → 피크 0.26.
//    그래서 라벨에 봉 수를 병기하던 안전장치도 필요 없어져 뺐다)
//
// [LV9] ⚠ **현재 화면에 뜨는 줄은 상위3 / 평균 / 총량 셋이다** (2026-08-13 사용자 지정).
//   같은 날 두 번 바뀌었으니 순서대로 읽을 것:
//     ① 피크 하나 → ② 피크·상위3·평균 세 줄([LV8]) → ③ **피크 제거 + 총량 추가**(지금)
//   - **피크(봉 하나) 줄은 뺐다.** 계산은 남아 있지만(top3를 구하며 어차피 나온다)
//     라벨에는 안 띄운다. LEG_VOL_METRICS에 다시 넣지 말 것 — 아래 [LV8]의 실측이
//     "봉 하나가 레그 거래량의 중앙값 37%를 대표한다"는 문제를 보여준 뒤 내린 결정이다.
//   - **총량(sum)은 그 방향 봉 거래량을 전부 더한 값**이다. [LV2]가 "합계 금지"라고
//     적어둔 그 값이 맞다 — 사용자가 알고 요청했다. 다만 **길이 편향은 실재한다**
//     (봉 수와의 상관계수 총량 0.29 vs 평균 0.00 / 상위3 0.10). 즉 총량이 늘었을 때
//     "거래가 많았다"인지 "레그가 길었다"인지는 위 두 줄과 같이 봐야 갈린다.
//     그래서 총량을 **맨 아래**에 두고 평균·상위3을 위에 남겨둔 것이다. 순서를 뒤집지 말 것.
//
// [LV8] 한때 **피크 / 상위3봉 평균 / 평균** 세 줄이었다 (2026-08-13). 근거는 아래 실측이고,
//   지금도 상위3·평균이 남아 있는 이유가 이것이다 (피크만 [LV9]로 빠졌다).
//   피크는 정의상 **봉 하나**라, 뉴스·청산 한 방이 레그 전체의 판정을 결정한다는
//   찝찝함이 남는다. 실측이 그걸 뒷받침했다 (BTC 15m/1h/4h/1d 각 1500봉, 레그 685개):
//     · 피크 1봉이 그 레그 같은방향 총거래량의 **중앙값 37%** 를 혼자 차지
//       (중앙 봉의 1.6배, 상위 10%는 3.8배)
//     · 같은방향 봉이 1개뿐인 레그가 9%, 2개 이하가 21%
//     · 직전 레그 대비 **↑↓ 부호가 갈리는 비율**: 상위3봉 11% / 평균 23% / 중앙값 31%
//       (예: 1h 하락 레그 peak +74% 인데 top3 −20%, mean −16%)
//   → 여러 지표를 **함께** 보여주고 해석은 사용자가 한다. 한 줄로 줄이지 말 것.
//   ※ 봉 수와의 상관계수: 피크 0.09 / 상위3 0.10 / 평균 0.00 / **총량 0.29**.
//     길이에 휘둘리는 건 총량뿐이라, 그래서 총량은 맨 아래고 위 두 줄이 대조군이다 [LV9].
//   ※ 봉이 3개 미만인 레그(21%)는 상위3 = 있는 만큼의 평균이라 평균과 같아지고,
//     1봉짜리(9%)는 세 값이 전부 같아진다. 그 경우에도 세 줄 다 띄운다 —
//     줄이 사라지면 "왜 안 뜨지"가 되고, 값이 같다는 것 자체가 "1봉짜리 레그"라는 정보다.
//
// [LV3] 레그의 봉 범위는 **(i1, i2]** — 시작 꼭짓점 봉은 제외, 끝 꼭짓점 봉은 포함.
//   시작 봉은 직전 레그의 끝 봉이라, 포함하면 이웃한 두 레그가 같은 봉을 공유해
//   같은 피크가 양쪽에 잡힐 수 있다. 레그끼리 비교하는 게 목적이라 겹침이 없어야 한다.

/**
 * 레그 (i1, i2] 구간의 거래량 요약 — **캔들 색 기준**.
 *
 * 방향별로 `{ peak, idx, top3, mean, sum, n }`:
 *   top3  상위 3봉 평균 (n<3이면 있는 만큼) — 한 방 의존을 던 값 [LV8]
 *   mean  그 방향 봉 전체의 평균    — 봉당 압력 (길이와 무관)
 *   sum   그 방향 봉 전체의 합      — 이 레그에 실제로 실린 총 거래량 [LV9]
 *   peak  가장 큰 봉 하나 (+ idx)   — **라벨에는 안 쓴다** [LV9]. top3를 구하며 어차피
 *                                    나오는 값이라 남겨둔 것뿐이다
 *
 * [LV4] 피크 하나만 내면 그게 양봉인지 음봉인지 알 수 없어서 해석이 안 된다
 *   (사용자 지적). 그래서 방향별로 나눠 둘 다 낸다.
 *   봉 하나는 양봉이거나 음봉이라 **둘 중 한쪽에만** 들어간다.
 *   ※ 해당 봉이 아예 없는 레그가 있다(짧은 레그). 그때 그쪽은 null이고
 *     라벨에서도 빠진다 — 0으로 채우면 "피크가 0"으로 읽혀서 틀린 말이 된다.
 *
 * [LV5] **테이커(체결 주체) 기준은 없다** — 2026-08-13 사용자 요청으로 제거.
 *   한때 캔들 기준과 나란히 두 줄로 보여주며 어느 쪽이 쓸모 있는지 비교했고,
 *   결론은 캔들 기준만 남긴다였다. 다시 넣지 말 것.
 *   (되살리려면 useCandles의 `bv` 파싱 — klines k[9] / WebSocket k.V — 부터 필요하다.
 *    그것도 같이 지웠다)
 *
 * [LV6] 계산은 **양쪽 다 하지만** 화면에는 레그 방향에 맞는 쪽만 뜬다
 *   (상승 레그 → up, 하락 레그 → dn). 고르는 곳은 useChartInteraction.
 *   여기서 미리 걸러내지 말 것 — 이 함수는 순수 계산이고 무엇을 보여줄지는 표시 정책이다.
 *   반대쪽도 값 자체는 의미가 있어(상승 레그 안의 최대 되돌림 봉) 언제든 다시 켤 수 있게 둔다.
 *
 * @param candles candlesRef.current 권장 (진행 중 봉 반영)
 * @returns { bars, up, dn } | null   (각 방향은 { peak, idx, top3, mean, n } | null)
 */
export function legPeakVolume(candles, i1, i2) {
  if (!candles?.length) return null;
  const a = Math.round(Math.min(i1, i2));
  const b = Math.round(Math.max(i1, i2));
  const lo = Math.max(0, a + 1);                    // [LV3] 시작 봉 제외
  const hi = Math.min(candles.length - 1, b);
  if (hi < lo) return null;

  // 상위 3개는 정렬 없이 슬롯 3개로 받는다 — 이 함수는 마우스가 움직일 때마다 돈다
  // (레그가 수백 봉이어도 배열 복사·정렬이 생기지 않게)
  const acc = () => ({ t: [0, 0, 0], idx: -1, sum: 0, n: 0 });
  const push = (s, v, i) => {
    if (v > s.t[0])      { s.t[2] = s.t[1]; s.t[1] = s.t[0]; s.t[0] = v; s.idx = i; }
    else if (v > s.t[1]) { s.t[2] = s.t[1]; s.t[1] = v; }
    else if (v > s.t[2]) { s.t[2] = v; }
    s.sum += v; s.n++;
  };
  const done = s => {
    if (s.n === 0) return null;
    const k = Math.min(3, s.n);
    let top = 0;
    for (let j = 0; j < k; j++) top += s.t[j];
    return { peak: s.t[0], idx: s.idx, top3: top / k, mean: s.sum / s.n, sum: s.sum, n: s.n };
  };

  const up = acc(), dn = acc();
  for (let i = lo; i <= hi; i++) {
    const c = candles[i];
    if (c.c >= c.o) push(up, c.v, i);
    else            push(dn, c.v, i);
  }
  return { bars: hi - lo + 1, up: done(up), dn: done(dn) };
}

