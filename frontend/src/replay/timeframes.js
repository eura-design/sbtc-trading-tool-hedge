// 리플레이 타임프레임 — 표시 TF와 **구동(drive) TF**
//
// ── 구동 TF가 왜 필요한가 ────────────────────────────────────────────────
// 봉 하나를 통째로 띄우면 그 봉 안에서 고가와 저가 중 **뭐가 먼저였는지 알 수 없다**.
// TP와 SL이 같은 봉 범위에 둘 다 들어가면 어느 쪽이 체결됐는지 정할 수 없어서,
// 트레이딩뷰 리플레이는 규칙(보통 SL 우선)으로 때운다. 그게 리플레이 성적을
// 실제보다 나쁘게(혹은 좋게) 만든다.
//
// 여기서는 1h 봉 하나를 5m 12개로 나눠 **순서대로** 흘려보낸다. 고가가 먼저면
// TP가 먼저 체결되고, 저가가 먼저면 SL이 먼저 체결된다 — 실제와 같은 판정이다.
//
// ── 실측 (2026-08-14, BTCUSDT) ───────────────────────────────────────────
//   1h/5m 구동, 3개월 2208봉 | 4h/15m 구동, 6개월 1104봉
//
//   | | 1h | 4h |
//   |---|---|---|
//   | 고가 먼저 | 48.4% | 45.6% |
//   | 저가 먼저 | 51.1% | 53.9% |
//   | 같은 구동봉 안 (순서 불명) | 0.5% | 0.5% |
//
// ⚠ 위 수치는 **BTCUSDT에서 잰 것**이다 (2026-09-02 기준 다른 코인은 안 쟀다).
//   변동성이 큰 코인일수록 "같은 구동봉 안" 비율이 조금 올라갈 수 있지만,
//   결론(구동 TF가 대부분의 순서를 밝힌다)은 가격대와 무관하다 —
//   한 봉을 12조각으로 나누는 것이 이 방식의 전부이기 때문이다.
//
// **구동 TF로 99.5%의 봉에서 순서가 밝혀진다.** 그리고 고가·저가 중 뭐가 먼저인지는
// 거의 반반이라, "SL 우선" 같은 고정 규칙은 모호한 봉의 **절반에서 틀린다**.
// 봉 단위 재생으로 되돌리면 그 절반이 통째로 추측이 된다.
//
// ⚠ 남는 0.5%(고가·저가가 같은 구동봉 안)는 이 방식으로도 못 가른다. 그 경우엔
//   결국 규칙이 필요하다 — 4단계 체결 엔진에서 보수적으로(SL 우선) 처리한다.
//
// ── 1m을 constants.TF_MS에 넣지 않는 이유 ────────────────────────────────
// 그 객체는 INTERVALS(차트가 고를 수 있는 TF 목록)와 짝을 이루고, 지표 메뉴의
// TfGrid·NotificationMenu·usePivotLevels가 전부 그 목록을 훑는다. 1m을 그쪽에 끼우면
// 리플레이와 무관한 화면에 1m 행이 생긴다. 리플레이 전용 값은 여기서만 늘린다.

import { TF_MS } from "../constants.js";

export const REPLAY_TF_MS = { "1m": 60_000, ...TF_MS };

export const tfMs = (tf) => REPLAY_TF_MS[tf];

/**
 * 표시 TF → 구동 TF.
 *
 * **봉 하나가 12~42틱으로 열리도록** 골랐다. 너무 촘촘하면(1h를 1m로 구동) 데이터가
 * 12배로 늘고 봉 하나 넘기는 데 60번을 눌러야 한다. 너무 성기면(4h를 1h로) 틱이
 * 4개뿐이라 intrabar 순서를 사실상 못 본다.
 *
 * 5m만 5틱인데, 바이낸스 선물 klines의 최소 단위가 1m이라 이보다 잘게 못 쪼갠다.
 */
export const DRIVE_TF = {
  "5m":  "1m",   //  5틱
  "15m": "1m",   // 15틱
  "1h":  "5m",   // 12틱
  "4h":  "15m",  // 16틱
  "1d":  "1h",   // 24틱
  "1w":  "4h",   // 42틱
  "1M":  "1d",   // ~30틱
};

export const driveTfFor = (tf) => DRIVE_TF[tf] ?? tf;

/** 표시 TF 봉 하나에 들어가는 구동 봉 수 (1M은 달 길이가 달라 근사값) */
export const ticksPerBar = (tf, drive = driveTfFor(tf)) =>
  Math.round(tfMs(tf) / tfMs(drive));
